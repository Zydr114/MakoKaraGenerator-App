using System.Globalization;
using System.Text.Json;
using MakoKaraGenerator.Core.Effects;
using MakoKaraGenerator.Core.Lyrics;
using MakoKaraGenerator.Core.Projects;
using MakoKaraGenerator.Core.Time;
using MakoKaraGenerator.Rendering;

internal static class M08Fixture
{
    internal const string Id = "m08-two-token-cjk-ruby-v1";
    internal const string Font = "Noto Sans CJK SC";
    internal const ulong Seed = 0x0123_4567_89ab_cdef;
    internal static readonly long[] Starts = [0, 180_000_000, 600_000_000];
    private static readonly string[] TokenTexts = ["星", "光"];
    private static readonly string[] RubyTexts = ["ほし", "ひかり"];

    internal static string Parameters(string sample) => sample switch
    {
        "CursorTrail" => """{"rateShape":"fixed","rate":60,"lifeUs":600000,"spreadPx":2,"transition":"jump"}""",
        "VectorTrail" => """{"mode":"ribbon","rate":24,"lifeUs":600000,"spreadPx":2,"showBirths":true,"sampling":"exact","transition":"jump"}""",
        "EventBurst" => """{"anchor":"token","scope":"project","count":3,"everyNth":1,"minimumDurationUs":0,"lifeUs":600000,"spreadPx":2}""",
        _ => throw new ArgumentOutOfRangeException(nameof(sample)),
    };

    internal static ProjectSnapshot Snapshot(EffectPackageContents package, string export, string sample)
    {
        var lines = Starts.Select((start, index) =>
        {
            string id = "m08-line-" + index.ToString(CultureInfo.InvariantCulture);
            var first = LyricToken.Create(id + "-star", "星", new(start, start + 1_000_000), TimingStatus.Edited);
            var second = LyricToken.Create(id + "-light", "光", new(start + 1_000_000, start + 2_000_000), TimingStatus.Edited);
            return LyricLine.Create(id, "星光", new(start, start + 2_000_000), TimingStatus.Edited, [first, second])
                with { RubyAnnotations = [RubyAnnotation.Create(id + "-ruby-star", first.Id, "ほし"),
                    RubyAnnotation.Create(id + "-ruby-light", second.Id, "ひかり")] };
        });
        var project = Project.Create("M08 finite particles", Composition.Create(640, 360, FrameRate.Fps30,
            outputDurationUs: 606_000_000), LyricsDocument.Create(lines),
            lyricStyle: LyricStyle.Default with { FontFamilyName = Font, FontSizePx = 64, Stroke = null, Shadow = null, Glow = null });
        return ProjectSnapshot.FromProject(project with { EnterAnimation = null,
            Effects = new([package], [new() { Id = "m08-effect", Name = "M08 fixed sample", PackageId = package.PackageId,
                Revision = package.Revision, ExportId = export, Subscription = new("project"), Seed = Seed,
                Parameters = EffectParameterOverrides.Parse(Parameters(sample)) }]) });
    }

    // These are sampling coordinates for the explicit fixture parameters, not assertions generated by the algorithm.
    internal static long[] Times(string sample)
    {
        long first = sample switch { "CursorTrail" => 16_667, "VectorTrail" => 41_667, "EventBurst" => 0,
            _ => throw new ArgumentOutOfRangeException(nameof(sample)) };
        long lastDeath = sample switch { "CursorTrail" => 2_583_334, "VectorTrail" => 2_558_334, _ => 1_600_000 };
        long[] offsets = [0, first - 1, first, first + 1, first + 599_999, first + 600_000, first + 600_001,
            750_000, 999_999, 1_000_000, 1_000_001, 1_999_999, 2_000_000, lastDeath - 1, lastDeath, lastDeath + 1];
        return [.. Starts.SelectMany(start => offsets.Where(static offset => offset >= 0).Select(offset => start + offset)
            .Concat(start == 0 ? [] : new[] { start - 1 })).Distinct().Order()];
    }

    internal static QueryOrder[] Orders(long[] times)
    {
        // Alternating the two ends starts at 600 s, then 0 s, repeatedly crossing the long gaps.
        List<long> shuffled = []; int low = 0, high = times.Length - 1;
        while (low <= high)
        {
            shuffled.Add(times[high--]);
            if (low <= high) shuffled.Add(times[low++]);
        }
        return [new("ascending", times), new("shuffled", [.. shuffled])];
    }

    internal static byte[] Serialize(string sample, ProjectSnapshot snapshot, long[] times, QueryOrder[] orders)
    {
        using var parameters = JsonDocument.Parse(Parameters(sample));
        return JsonSerializer.SerializeToUtf8Bytes(new { schema = Id, sample, snapshot.EffectInputsFingerprint,
            width = 640, height = 360, outputDurationUs = 606_000_000, fps = "30/1", outputMode = "Transparent",
            lineStartsUs = Starts, tokenDurationUs = 1_000_000, tokenTexts = TokenTexts,
            rubyTexts = RubyTexts, font = Font, fontSizePx = 64, stroke = false, shadow = false, glow = false,
            enterAnimation = false, seed = Seed.ToString("x16", CultureInfo.InvariantCulture),
            instance = "m08-effect", binding = "project", subscription = "project", parameters = parameters.RootElement,
            timesUs = times, orders = orders.Select(static order => new { name = order.Name, timesUs = order.Times }),
            boundaryScope = "First birth, its death, token handoff, source end and final death at -1/0/+1 us where nonnegative. Coordinates are fixture sampling choices, not expected algorithm output.",
        });
    }
}

internal sealed record QueryOrder(string Name, long[] Times);
