#!/usr/bin/env python3
"""Explicit, isolated real-HTTP cancellation and Worker recovery probe."""
import argparse
import copy
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import sys
import time
from urllib.parse import urlencode
import zipfile

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
SPEC = importlib.util.spec_from_file_location("seek_probe", HERE / "probe.py")
seek = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(seek)
save_json = seek.save_json


class CancellationProbe(seek.SeekProbe):
    def prepare_template(self):
        directory = seek.ROOT / "samples/ScriptEffects/WordEmphasis"
        manifest = json.loads((directory / "manifest.json").read_text())
        source_path = "src/WordEmphasis.cs"
        # C# string literal generated by JSON escaping. The marker path belongs
        # to this run, and the probe never embeds or records credentials.
        marker = json.dumps(str(self.output / "markers"), ensure_ascii=True)
        source = '''using System;
using System.IO;
using MakoKaraGenerator.Scripting;
public sealed class WordEmphasis : EffectBase
{
    private readonly string instance = Guid.NewGuid().ToString("N");
    private static readonly string root = MARKER;
    public override void Evaluate(FrameContext frame, FrameWriter output)
    {
        string identity = Environment.ProcessId.ToString() + "|" + instance;
        if (frame.TimeUs == 1000000)
            File.WriteAllText(Path.Combine(root, "evaluated-" + instance), identity);
        if (frame.TimeUs == 2000000 && File.Exists(Path.Combine(root, "armed")))
        {
            File.WriteAllText(Path.Combine(root, "started"), identity);
            frame.CancellationToken.WaitHandle.WaitOne();
            File.WriteAllText(Path.Combine(root, "canceled"), identity);
            frame.CancellationToken.ThrowIfCancellationRequested();
        }
    }
}
'''.replace("MARKER", marker).encode()
        files = {entry["path"]: (source if entry["path"] == source_path else (directory / entry["path"]).read_bytes())
                 for entry in manifest["files"]}
        for entry in manifest["files"]:
            entry["sha256"] = hashlib.sha256(files[entry["path"]]).hexdigest()
        archive = io.BytesIO()
        with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as package:
            package.writestr("manifest.json", json.dumps(manifest, ensure_ascii=False))
            for path, data in files.items():
                package.writestr(path, data)
        asset = self.upload("cancel-package", "cancel-fixture.mkfx", "application/octet-stream", archive.getvalue())
        inspected = self.request("cancel-inspect", "POST", "/api/v1/effect-packages/inspect", value={"packageAssetId": asset["assetId"]})
        self.check(inspected["structureValid"], "cancel fixture package structure valid")
        draft = self.request("cancel-draft", "POST", "/api/v1/drafts", status=201, value={
            "packageAssetId": asset["assetId"], "exportId": "word-emphasis", "name": "HTTP cancellation fixture"})
        self.check(draft["canCompile"], "cancel fixture contains C# controller")
        builtin = self.request("cancel-builtin", "GET", "/api/v1/template-libraries/builtin/templates")
        base = next(item for item in builtin["templates"] if item["kind"] == "line")
        detail = self.request("cancel-detail", "GET", "/api/v1/template-libraries/builtin/templates/detail?" + urlencode({
            "expectedRevision": builtin["revision"], "templateId": base["templateId"]}))
        definition = copy.deepcopy(detail["definition"])
        config = draft["configuration"]
        definition.update(name="HTTP cancellation fixture", kind="line", properties=["opacity"], packages=[inspected["reference"]])
        definition["effectRecipes"] = [{"recipeId": "cancel-controller", "name": "Cancellation controller",
            "target": config["relativeTarget"], "packageId": config["packageId"], "revision": config["sourceRevision"],
            "exportId": config["exportId"], "parametersJson": config["parametersJson"], "enabled": True,
            "overlayLayer": config["overlayLayer"], "readScope": config["readScope"],
            "branchInput": config.get("branchInput"), "fixedSeed": config.get("fixedSeed"), "configurationId": None}]
        library = self.request("cancel-personal", "GET", "/api/v1/template-libraries/personal/templates")
        self.template = self.request("cancel-template", "POST", "/api/v1/template-libraries/personal/commands", value={
            "expectedRevision": library["revision"], "metadata": self.metadata("cancel-template"),
            "command": {"type": "create", "definitionFormat": "full", "definition": definition}})
        save_json(self.output / "fixture.json", {"archiveSha256": hashlib.sha256(archive.getvalue()).hexdigest(),
            "sourceSha256": hashlib.sha256(source).hexdigest(), "packageRevision": inspected["packageRevision"]})

    def marker(self, name):
        path = self.output / "markers" / name
        deadline = time.monotonic() + self.args.timeout_seconds
        while time.monotonic() < deadline:
            try:
                parts = path.read_text().split("|")
                if len(parts) == 2 and parts[0].isdigit() and len(parts[1]) == 32:
                    return {"pid": int(parts[0]), "instance": parts[1]}
            except OSError:
                pass
            time.sleep(self.args.poll_ms / 1000)
        raise TimeoutError(name + ": script marker not observed before deadline")

    def run_cancel(self):
        deployment = json.loads((self.dist / "deployment.json").read_text())
        save_json(self.output / "provenance.json", {"deployment": deployment,
            "probeSha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "dist": str(self.dist), "backend": self.args.backend})
        (self.output / "markers").mkdir()
        self.stage = "start"
        self.start("cancel")
        self.connect("cancel")
        self.check(self.current_ready["version"] == deployment["version"], "running version matches deployment")
        self.stage = "fixture"
        self.prepare_template()
        self.create_project("cancel", 8_000_000)
        hashes = {}
        self.stage = "reference"
        self.sample("reference", 1, 1_000_000, hashes)
        preview = self.active_preview
        path = "/api/v1/preview-sessions/" + preview["previewId"]
        revision, old_generation = preview["source"]["sourceRevision"], preview["previewGeneration"]
        (self.output / "markers/armed").touch()
        self.stage = "blocked-seek"
        accepted = self.request("blocked-seek", "POST", path + "/frame-requests", status=202, value={
            "expectedSourceRevision": revision, "previewGeneration": old_generation,
            "requestSeq": "2", "timeUs": "2000000", "intent": "seek"})
        preview["previewGeneration"] = accepted["previewGeneration"]
        self.check(accepted["previewId"] == preview["previewId"] and accepted["requestSeq"] == "2"
            and accepted["timeUs"] == "2000000" and accepted["state"] == "accepted"
            and int(preview["previewGeneration"]) > int(old_generation), "blocked seek exact accepted identity")
        self.stage = "barrier"
        started = self.marker("started")
        workers = self.workers()
        self.check(len(workers) == 1 and workers[0]["pid"] == started["pid"], "barrier executes in owned Worker")
        worker = {key: workers[0][key] for key in ("pid", "startTicks")}
        canceled_generation = preview["previewGeneration"]
        before = {p.name for p in (self.output / "markers").glob("evaluated-*")}
        (self.output / "markers/armed").unlink()
        self.stage = "recovery"
        self.sample("recovered", 3, 1_000_000, hashes)
        canceled = self.marker("canceled")
        self.check(canceled == started, "blocked controller observed its own cancellation token")
        after = self.workers()
        self.check(len(after) == 1 and {key: after[0][key] for key in worker} == worker,
            "same Worker PID and startTicks after recovery")
        recovered = [self.marker(p.name) for p in (self.output / "markers").glob("evaluated-*") if p.name not in before]
        self.check(any(item["pid"] == worker["pid"] and item["instance"] != started["instance"] for item in recovered),
            "new controller instance evaluated recovered frame in same Worker")
        self.request("stale-generation", "POST", path + "/frame-requests", status=409, code="previewGenerationConflict", value={
            "expectedSourceRevision": revision, "previewGeneration": canceled_generation,
            "requestSeq": "4", "timeUs": "1000000", "intent": "seek"})
        save_json(self.output / "cancellation.json", {"worker": worker, "started": started, "canceled": canceled,
            "recoveredInstances": recovered, "canceledGeneration": canceled_generation,
            "recoveredGeneration": preview["previewGeneration"], "referenceRgbaSha256": hashes[1_000_000]})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", action="store_true", help="explicitly start the isolated HTTP probe")
    parser.add_argument("--dist", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--width", type=int, default=320)
    parser.add_argument("--height", type=int, default=180)
    parser.add_argument("--timeout-seconds", type=float, default=90)
    parser.add_argument("--poll-ms", type=int, default=50)
    parser.add_argument("--backend", choices=("cpu", "gpu"), default="cpu")
    parser.add_argument("--ffmpeg", default="/usr/bin/ffmpeg")
    args = parser.parse_args()
    if not args.run:
        parser.error("--run is required to start the probe")
    if not args.dist or not args.output:
        parser.error("--dist and --output are required with --run")
    if not (64 <= args.width <= 2560 and 64 <= args.height <= 1440
            and 1 <= args.timeout_seconds <= 600 and 10 <= args.poll_ms <= 1000):
        parser.error("size/deadline/poll outside finite probe bounds")
    args.dist, args.output = args.dist.resolve(), args.output.resolve()
    args.require_reuse = True
    args.output.mkdir(parents=True, exist_ok=False)
    probe = CancellationProbe(args.output, args.dist, args)
    failures = []
    try:
        probe.run_cancel()
    except Exception as error:
        failures.append(probe.failure(error))
    finally:
        try:
            (args.output / "markers/armed").unlink(missing_ok=True)
            if probe.active_preview or probe.active_project:
                probe.close_resources("cancel")
        except Exception as error:
            failures.append(probe.failure(error, "resource-cleanup"))
        try:
            probe.stop("cancel")
        except Exception as error:
            failures.append(probe.failure(error, "owned-process-drain"))
        try:
            scanned = probe.scan_credentials()
        except Exception as error:
            failures.append(probe.failure(error, "credential-scan"))
            scanned = None
        summary = {"status": "failed" if failures else "passed", "failures": failures,
            "samples": probe.samples, "credentialScannedFiles": scanned,
            "httpRequests": probe.request_count, "assertions": len(probe.assertions)}
        save_json(args.output / "summary.json", summary)
        try:
            probe.scan_credentials()
        except Exception:
            summary["status"] = "failed"
            save_json(args.output / "summary.json", summary)
        print(json.dumps({"status": summary["status"], "failures": len(failures)}))
    return 0 if summary["status"] == "passed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
